    const Bl = [-P.RAIL_X, Y1, P.CHASSIS_Z || 0], Br = [P.RAIL_X, Y1, P.CHASSIS_Z || 0];   // bottom corners
    const Ll = [-hw, Y1, 0], Lr = [hw, Y1, 0];                          // lower side corners (deck ring)
    const faceNormal = (a, b, c) => { const n = new THREE.Vector3().crossVectors(v3(b).sub(v3(a)), v3(c).sub(v3(a))).normalize(); const centroid = v3(a).add(v3(b)).add(v3(c)).multiplyScalar(1 / 3); const out = centroid.clone().sub(toT(0, (Y1 + yt) / 2 - 20, zc)); return n.dot(out) < 0 ? n.negate() : n; };
