      halfDisc(c, top.sd, top.perp, 4.5, TOP.n, dark, 0.6); halfDisc(c, sid.sd, sid.perp, 4.5, tri.n, dark, 0.6);
      const b0 = lift(lerp(rim, tip, 0.33), TOP.n, 0.5), b1 = lift(lerp(rim, tip, 0.5), TOP.n, 0.5);
      const inward = top.perp.clone().multiplyScalar(14), bar = new THREE.BufferGeometry();
      const q = [b0, b1, b1.clone().addScaledVector(top.perp, 11).addScaledVector(top.sd, 4), b0.clone().add(inward).addScaledVector(top.sd, 7)];
