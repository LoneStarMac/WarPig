    const BOT = { a: Bl, b: Br, c: N.br, d: N.bl }; BOT.n = faceNormal(BOT.a, BOT.b, BOT.c);                 // chin
    const LOW = { l: { a: Bl, b: Ll, c: N.bl }, r: { a: Br, b: Lr, c: N.br } };                                // lower side triangles
